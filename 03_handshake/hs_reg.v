// 你未来项目里的"事件派发器"需要把事件从一个模块传到另一个模块。
// 两个模块的节奏不一样（上游突发、下游拥塞），中间就需要这样一个
// "弹性缓冲"来吸收节奏差，同时保证数据不丢、不重、不乱序。
//
// 运行：
//   bash run.sh          只仿真，看 PASS / FAIL
//   bash run.sh wave     仿真并把波形用 GTKWave 打开
//
//-----------------------------------------------------------------------------
// 握手协议（上游 / 下游）
//-----------------------------------------------------------------------------
//   上游（从你这里收数据）：
//       s_valid : 上游说"我这有数据"
//       s_ready : 你说"我可以收"
//       规则：当 s_valid && s_ready 同时为 1 的那个时钟上升沿，数据被接收
//   下游（你往外发数据）：
//       m_valid : 你说"我有数据要发"
//       m_ready : 下游说"我可以收"
//       规则：当 m_valid && m_ready 同时为 1 的那个时钟上升沿，数据被取走
//
//-----------------------------------------------------------------------------
// 行为规格（测试平台按这个检查）
//-----------------------------------------------------------------------------
//   1. 深度为 1 的寄存器缓冲（只能缓存 1 个数据）
//   2. 复位后 m_valid = 0
//   3. s_ready = (~m_valid) | m_ready
//         —— 输出寄存器空，或者下游能立刻取走时，才可以收新数据
//   4. 每个时钟上升沿：
//         if (s_ready)            m_valid <= s_valid;
//         if (s_ready && s_valid) m_data  <= s_data;
//   5. ★ 关键约束：m_valid 和 m_data 必须是寄存器输出，
//         不允许有从 s_valid 到 m_valid 的组合路径。
//         （否则上游的组合逻辑会一路串到下游，时序会崩。
//           这也是为什么 m_ready 组合出来给 s_ready 是允许的，
//           而 s_valid 不能组合到 m_valid。）
//
//-----------------------------------------------------------------------------
// 为什么这样写就对了（想清楚再看）
//-----------------------------------------------------------------------------
//   情况一：m_valid = 0（输出空）
//           s_ready = 1，任何 s_valid 都会在下一个上升沿变成 m_valid = 1
//   情况二：m_valid = 1 且 m_ready = 0（下游堵塞）
//           s_ready = 0，上游的数据收不进来（上游必须自己保持 s_valid）
//   情况三：m_valid = 1 且 m_ready = 1（下游正在取走）
//           s_ready = 1，同一个上升沿里：旧数据被下游取走，新数据换进来
//           —— 这就是"一拍顶一拍"，效率最高的情况
//
//=============================================================================

