// 练习 01：同步 FIFO  ——  你未来项目里的"事件队列"
//-----------------------------------------------------------------------------
// 目标：补完本模块，让 tb_fifo.v 打印 ">>> PASS <<<"
//
// 运行：
//   bash run.sh          只仿真，看 PASS / FAIL
//   bash run.sh wave     仿真并把波形用 GTKWave 打开
//
//-----------------------------------------------------------------------------
// 规格（测试平台按这个规格检查，必须完全一致）
//-----------------------------------------------------------------------------
//  1. 单时钟同步 FIFO，位宽 WIDTH，深度 DEPTH（DEPTH 必须是 2 的幂）
//  2. 复位 rst_n 为低电平有效，异步复位；复位后 empty=1, full=0, count=0
//  3. dout 是"组合读出"（show-ahead / first-word-fall-through）：
//     只要 FIFO 非空，dout 就立刻呈现队首数据，不需要先拉 rd_en。
//     也就是说：dout = mem[rptr]，是一个组合逻辑输出。
//  4. 写满时 wr_en 被忽略：不覆盖已有数据，count 不变
//  5. 读空时 rd_en 被忽略：rptr 不动，count 不变，dout 保持不变
//  6. 同一周期同时读和写时：count 保持不变
//  7. count 实时反映 FIFO 中元素个数
//
//-----------------------------------------------------------------------------
// 提示：两种都能做对的做法
//-----------------------------------------------------------------------------
//  做法 A（计数法，逻辑更直观，推荐先试这个）
//    - 用一个 count 寄存器记元素个数
//    - empty = (count == 0)
//    - full  = (count == DEPTH)
//    - 写逻辑： if (wr_en && !full)  mem[wptr] <= din; wptr <= wptr + 1;
//    - 读逻辑： if (rd_en && !empty) rptr <= rptr + 1;
//    - count 的更新要小心"同时读写"的情况，见下面的 TODO 3 警告
//
//  做法 B（指针法，经典写法）
//    - 读写指针各多一位（PTRW = AW + 1）
//    - empty = (wptr == rptr)
//    - full  = (wptr[AW-1:0] == rptr[AW-1:0]) && (wptr[AW] != rptr[AW])
//    - count = wptr - rptr（注意截断到位宽）
//
//-----------------------------------------------------------------------------
// 警告：新手最容易在这里翻车
//-----------------------------------------------------------------------------
//  如果你这样写 count：
//      if (wr_en && !full) count <= count + 1;
//      if (rd_en && !empty) count <= count - 1;
//  那么"同时读写"时，第二条非阻塞赋值会**覆盖**第一条，
//  count 会错误地减 1（应该是保持不变）。
//  测试平台的"阶段9"专门检查这个，请自己想办法处理。
//=============================================================================

`timescale 1ns/1ps

module fifo #(
    parameter WIDTH = 8,
    parameter DEPTH = 16,      // 必须是 2 的幂
    parameter CW = 8           // count 端口位宽：由接口契约决定（tb_fifo 按 8 位接）
                               // 注意：DEPTH 超过 255 时这里要一起加宽，否则会截断（会静默出错！）
)(
    input  wire             clk,//同步时钟
    input  wire             rst_n,//指针和计数器清零
    // ---- 写端口 ----
    input  wire             wr_en,//写使能
    input  wire [WIDTH-1:0] din,//写入fifo的数据//width-1：0表示这个定义这个信号有width个比特，编号从width-1到0
    output wire             full,//fifo满标志
    // ---- 读端口 ----
    input  wire             rd_en,//读使能
    output wire [WIDTH-1:0] dout,//从fifo出的数据
    output wire             empty,//fifo空标志，fifo里面没有数据不能读
    // ---- 状态 ----
    output wire [CW-1:0]    count//当前存了几个数据
);

    localparam AW   = $clog2(DEPTH);   // 地址位宽；算存储depth个单元最少需要几个地址线

    //=========================================================================
    // TODO 1：声明存储体和读写指针
    reg [WIDTH-1:0] mem [0:DEPTH-1];
    reg [AW-1:0]    wptr;//写指针
    reg [AW-1:0]    rptr;//读指针
    reg [CW-1:0]    cnt;//fifo里面的数据个数计数器

    wire do_wr, do_rd;//执行写操作的标志；执行读操作的标志
    assign do_wr = wr_en & ~full;       // 想写 且 没满
    assign do_rd = rd_en & ~empty;      // 想读 且 非空
     //=========================================================================
    //  TODO 4：组合输出（先把这几行写上，就能看到 z 变成数字）
    //=========================================================================

    // dout 直接接在 mem[rptr] 上：只要 FIFO 非空，队首数据就一直摆在端口上，
    // 下游随时能看。这叫"组合读出"，不需要先发 rd_en 才能看到数据。
    assign dout  = mem[rptr];//rptr读指针

    // 没有元素 = 空
    assign empty = (cnt == 0);

    // 元素个数达到 DEPTH = 满
    assign full  = (cnt == DEPTH);

    // 把内部计数器直接送出去，外面也能知道现在存了多少个
    assign count = cnt;
    //=========================================================================
    //  TODO 2：写指针
    //=========================================================================
    // 时序逻辑：只在时钟上升沿根据当前状态决定下一个值，所以用非阻塞赋值 <=。
    // 异步复位：rst_n 一拉低立刻清零，不用等时钟。
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            wptr <= {AW{1'b0}};        // 复位：指针回到 0 号位置
        end else if (do_wr) begin
            wptr <= wptr + 1'b1;       // 真的写了，指针往后挪一格；只有 AW 位，自动回绕
        end
        // 没写的时候什么都不做，指针自然保持不变
    end

    //=========================================================================
    //=========================================================================
    //  TODO 3：读指针
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rptr <= {AW{1'b0}};        // 复位：指针回到 0 号位置
        end else if (do_rd) begin
            rptr <= rptr + 1'b1;       // 真的读了，队首往后挪一格
        end
    end

    //=========================================================================
    //  存储体写入
    //=========================================================================
    // 注意这里没有复位：复位时不需要把 16 个存储单元逐个清零（太浪费硬件），
    // 因为只有"写过的位置"才会被读，而读的前提是 cnt > 0，说明已经写过了。
    always @(posedge clk) begin
        if (do_wr) begin
            mem[wptr] <= din;          // 把 din 存进当前写入位置
        end
    end

    //=========================================================================
    //  元素计数：这里是最容易写错的地方
    //=========================================================================
    // 为什么不能写成两个并列的 if？
    //     if (do_wr) cnt <= cnt + 1;
    //     if (do_rd) cnt <= cnt - 1;
    // 因为非阻塞赋值是"最后一次赋值生效"。如果同一周期读和写同时发生，
    // 第二句会覆盖第一句，cnt 会错误地减 1（正确行为应该是不变）。
    //
    // 所以用 case 一次性把四种情况都列清楚，不留覆盖的可能。
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt <= {CW{1'b0}};         // 复位：一个元素都没有
        end else begin
            case ({do_wr, do_rd})       // 把两个信号拼成 2 位，一次比较
                2'b10:   cnt <= cnt + 1'b1;   // 只写      -> 多一个
                2'b01:   cnt <= cnt - 1'b1;   // 只读      -> 少一个
                default: cnt <= cnt;          // 同时读写 / 都不做 -> 不变
            endcase
        end
    end
endmodule
