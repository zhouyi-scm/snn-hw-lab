// 练习 02：带泄漏的膜电位累加器 —— LIF 神经元的心脏
//-----------------------------------------------------------------------------
// 这是你最终项目里最核心的一个模块。做完它，你就同时理解了
// "泄漏（leak）" 和 "事件驱动（event-driven）" 在硬件上到底长什么样。
//
// 运行：
//   bash run.sh          只仿真，看 PASS / FAIL
//   bash run.sh wave     仿真并把波形用 GTKWave 打开
//
//-----------------------------------------------------------------------------
// 行为规格（测试平台按这个检查）
//-----------------------------------------------------------------------------
//   每个时钟上升沿：
//       if (en)  v_out <= v_out - (v_out >>> SHIFT) + i_in;
//       else     v_out <= v_out;      // 保持不变 —— 这就是稀疏性省电的来源
//   异步低电平复位时：
//       v_out <= 0
//
//   注意：右边的 v_out 都是"旧值"（当前寄存器里的值），
//        所以要用非阻塞赋值 <=，不要用 =。
//
//-----------------------------------------------------------------------------
// 为什么写成 v - (v >>> SHIFT) 而不是 v * beta
//-----------------------------------------------------------------------------
//   取 beta = 1 - 2^-SHIFT，于是
//       v * beta  =  v - v * 2^-SHIFT  =  v - (v >>> SHIFT)
//   一次乘法被换成了"一次移位 + 一次减法"，硬件上几乎免费
//   （不需要 DSP，只需要几根线和几个逻辑门）。
//   例：SHIFT = 4 时 beta = 1 - 1/16 = 0.9375
//
//   这是低功耗 AI 芯片里最典型的思路：把算法改写成硬件友好的形式，
//   而不是硬堆乘法器。你未来会反复用到这个思想。
//
//-----------------------------------------------------------------------------
// 两个必须注意的坑
//-----------------------------------------------------------------------------
//   1. v_out 和 i_in 都必须是 signed（有符号），否则负数会算错
//   2. 必须用 >>> （算术右移，保留符号位），
//      不能用 >> （逻辑右移，负数会变成很大的正数）
//      测试平台里有专门的负数衰减用例，用错必挂
//
//-----------------------------------------------------------------------------
// 只有 4 行逻辑，请自己想清楚再写
//=============================================================================

`timescale 1ns/1ps

module lif_leak #(
    parameter WIDTH = 16,       // 膜电位位宽
    parameter SHIFT = 4         // beta = 1 - 2^-SHIFT
)(
    input  wire                    clk,
    input  wire                    rst_n,      // 异步低电平复位
    input  wire                    en,         // 1 = 本周期该神经元参与更新（有事件）
    input  wire signed [WIDTH-1:0] i_in,      // 输入电流（来自突触的加权脉冲）
    output reg  signed [WIDTH-1:0] v_out      // 膜电位
);

    //=========================================================================
    // 实现：4 行时序逻辑
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 异步复位：rst_n 低电平有效，所以敏感列表里也是 negedge
            v_out <= {WIDTH{1'b0}};
        end else if (en) begin
            // 泄漏 + 累加。右边的 v_out 是寄存器的"旧值"，
            // 整个表达式在同一个时钟沿同时生效，所以必须用非阻塞 <=
            v_out <= v_out - (v_out >>> SHIFT) + i_in;
        end
        // en == 0：什么都不写。
        // 寄存器自动保持 —— 综合出来就是 FDCE 的 CE 端被拉低，
        // 16 个触发器一个都不翻转，这就是"事件驱动"省电的来源。
    end

endmodule
